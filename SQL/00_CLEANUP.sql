-- Xóa VPD Policies
BEGIN
    DBMS_RLS.DROP_POLICY('BVOWNER', 'NHANVIEN', 'POL_NV_SELF');
    DBMS_RLS.DROP_POLICY('BVOWNER', 'BENHNHAN', 'POL_BN_SELF');
    DBMS_RLS.DROP_POLICY('BVOWNER', 'HSBA', 'POL_HSBA_BACSI');
    DBMS_RLS.DROP_POLICY('BVOWNER', 'HSBA_DV', 'POL_HSBADV_KTV');
    DBMS_RLS.DROP_POLICY('BVOWNER', 'BENHNHAN', 'POL_BN_BACSI');
    DBMS_RLS.DROP_POLICY('BVOWNER', 'DONTHUOC', 'POL_DT_BACSI');
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- Xóa package VPD
BEGIN
    EXECUTE IMMEDIATE 'DROP PACKAGE BVOWNER.BV_VPD_PKG';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- Xóa tables (cascade)
