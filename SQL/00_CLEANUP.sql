    EXECUTE IMMEDIATE 'DROP TABLE BVOWNER.HSBA_DV CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE BVOWNER.HSBA CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE BVOWNER.BENHNHAN CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE BVOWNER.NHANVIEN CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE BVOWNER.THONGBAO CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- Xóa views
BEGIN
    EXECUTE IMMEDIATE 'DROP VIEW BVOWNER.V_CURRENT_NHANVIEN';
    EXECUTE IMMEDIATE 'DROP VIEW BVOWNER.V_CURRENT_BENHNHAN';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- Xóa sequences
BEGIN
    EXECUTE IMMEDIATE 'DROP SEQUENCE BVOWNER.SEQ_MANV';
    EXECUTE IMMEDIATE 'DROP SEQUENCE BVOWNER.SEQ_MABN';
    EXECUTE IMMEDIATE 'DROP SEQUENCE BVOWNER.SEQ_MAHSBA';
    EXECUTE IMMEDIATE 'DROP SEQUENCE BVOWNER.SEQ_MATB';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- Xóa users mẫu (nhân viên + bệnh nhân)
DECLARE
    CURSOR c_users IS
        SELECT username FROM dba_users
        WHERE username LIKE 'BS_%' OR username LIKE 'DPV_%'
           OR username LIKE 'KTV_%' OR username LIKE 'BN_%'
           OR username LIKE 'OLS_U%'
           OR username = 'BVOWNER';
BEGIN
    FOR r IN c_users LOOP
        EXECUTE IMMEDIATE 'DROP USER "' || r.username || '" CASCADE';
    END LOOP;
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- Xóa OLS policy cũ
BEGIN
    LBACSYS.SA_SYSDBA.DROP_POLICY('BV_POLICY');
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- Xóa roles
